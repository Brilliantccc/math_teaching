# 题目提取提示词（完整版，包含答案解析生成）
EXTRACT_PROMPT = """识别图片中的数学题，返回JSON数组。同时为每道题生成答案和解析。

每道题包含：
- content: 题干+选项（如有图用{{img:0}}引用，中文用$\\text{}$包裹，公式用$$包裹）
- image_descriptions: 图的描述数组
- image_regions: 图在原图的位置[x1,y1,x2,y2]，0-1比例值，无图返回[]
- answer_analysis: 答案和解析（格式：$\\text{答案}$\\n---解析---\\n$\\text{解析}$）
- difficulty: 1简单/2中等/3困难
- category: 几何/代数/函数等
- question_type: 选择题/填空题/解答题/判断题/计算题

规则：
1. 识别所有独立题目，必须包含完整选项A/B/C/D（选择题）
2. 每题的图只属于该题，精确定位图片区域
3. **图片位置说明**："如图"只是中文数学题的习惯用语，{{img:N}}应放在图片实际描述的内容位置，不要机械地跟在"如图"后面。图片通常放在题干末尾（选项之前）
4. **必须为每道题生成完整的答案和解析**
5. **解析要简洁精炼，直接给出关键解题步骤，不要输出思考过程**
6. 解析长度控制在200字以内，只保留核心推导
7. **根据题目形式准确判断题型**：
   - 有A/B/C/D选项 → 选择题
   - 有下划线或括号需要填写 → 填空题
   - 要求"证明"、"求解"、"画图"、"解答"等 → 解答题
   - 要求判断对错 → 判断题
   - 纯计算题目 → 计算题

返回格式示例：
[{"content":"如图，在$\\text{三角形}ABC$中，已知$AB=5$，$BC=12$，$AC=13$。$\\text{求三角形}ABC$的面积。\\n{{img:0}}\\nA.30\\nB.60\\nC.78\\nD.156","image_descriptions":["直角三角形ABC示意图"],"image_regions":[[0.1,0.2,0.4,0.5]],"answer_analysis":"$\\text{答案}$：A\\n---解析---\\n$\\text{因为}5^2+12^2=13^2\\text{，所以三角形}ABC\\text{是直角三角形，面积}=\\frac{1}{2}\\times5\\times12=30$","difficulty":2,"category":"几何","question_type":"选择题"}]

只返回JSON，不要包含任何解释或思考过程"""


